"""
app.py
------
Streamlit deployment UI for the Loan Approval Prediction project.

This file does NOT modify main.py or anything in src/ — it only imports
from them. It reuses:
    * main.predict_single()          for scoring a custom applicant
    * main.main()                    to train the model once, if no saved
                                      artifacts exist yet (first run only)
    * outputs/*.joblib               the saved model + scaler from a
                                      previous `python main.py` run, if
                                      present (skips retraining)
    * outputs/*.png                  the EDA / evaluation plots already
                                      generated by main.py

Run locally:
    streamlit run app.py

Deploy on Streamlit Community Cloud:
    1. Push this whole project (including app.py) to a GitHub repo.
    2. On share.streamlit.io, point it at the repo with main file "app.py".
    3. Add a requirements.txt entry for "streamlit" (see note at bottom).
"""

import json
import os
import sys

import joblib
import pandas as pd
import streamlit as st

# Make src/ importable, exactly like main.py does.
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(BASE_DIR, "src"))

import main as pipeline  # noqa: E402  (imports main.py unchanged)

OUT_DIR = os.path.join(BASE_DIR, "outputs")
MODEL_PATH = os.path.join(OUT_DIR, "logistic_regression_model.joblib")
SCALER_PATH = os.path.join(OUT_DIR, "scaler.joblib")
METRICS_PATH = os.path.join(OUT_DIR, "metrics.json")
IMPORTANCE_PATH = os.path.join(OUT_DIR, "feature_importance.csv")

st.set_page_config(page_title="Loan Approval Prediction", page_icon="🏦", layout="wide")


@st.cache_resource(show_spinner="Loading model (training once if needed)...")
def load_model_and_scaler():
    """
    Load the trained model + scaler saved by main.py's own pipeline.
    If they don't exist yet (first deploy, no outputs/ committed), run the
    exact same main.main() pipeline once to produce them. Either way, the
    original pipeline code is what does the work — this function only
    decides whether it needs to be (re-)run.
    """
    if not (os.path.exists(MODEL_PATH) and os.path.exists(SCALER_PATH)):
        pipeline.main()  # runs the unmodified end-to-end pipeline from main.py

    model = joblib.load(MODEL_PATH)
    scaler = joblib.load(SCALER_PATH)
    return model, scaler


@st.cache_data
def load_metrics():
    if os.path.exists(METRICS_PATH):
        with open(METRICS_PATH) as f:
            return json.load(f)
    return None


@st.cache_data
def load_importance():
    if os.path.exists(IMPORTANCE_PATH):
        return pd.read_csv(IMPORTANCE_PATH)
    return None


model, scaler = load_model_and_scaler()

st.title("🏦 Loan Approval Prediction")
st.caption("Logistic Regression model — same pipeline as `main.py`, served interactively.")

tab_predict, tab_performance, tab_eda = st.tabs(
    ["🔮 Predict", "📊 Model Performance", "🔍 EDA Plots"]
)

# ----------------------------------------------------------------------
# TAB 1: Predict
# ----------------------------------------------------------------------
with tab_predict:
    st.subheader("Score a new applicant")

    with st.form("applicant_form"):
        col1, col2, col3 = st.columns(3)

        with col1:
            gender = st.selectbox("Gender", ["Male", "Female"])
            married = st.selectbox("Married", ["Yes", "No"])
            dependents = st.selectbox("Dependents", ["0", "1", "2", "3+"])
            education = st.selectbox("Education", ["Graduate", "Not Graduate"])

        with col2:
            self_employed = st.selectbox("Self Employed", ["No", "Yes"])
            applicant_income = st.number_input("Applicant Income (monthly)", min_value=0, value=5000, step=100)
            coapplicant_income = st.number_input("Coapplicant Income (monthly)", min_value=0, value=1500, step=100)
            loan_amount = st.number_input("Loan Amount (in thousands)", min_value=1, value=120, step=1)

        with col3:
            loan_amount_term = st.selectbox(
                "Loan Amount Term (months)",
                [12, 36, 60, 84, 120, 180, 240, 300, 360, 480], index=8,
            )
            credit_history = st.selectbox(
                "Credit History", [1.0, 0.0],
                format_func=lambda x: "Meets guidelines (1)" if x == 1.0 else "Does not meet guidelines (0)",
            )
            property_area = st.selectbox("Property Area", ["Urban", "Semiurban", "Rural"])

        submitted = st.form_submit_button("Predict", type="primary", use_container_width=True)

    if submitted:
        applicant = {
            "Gender": gender,
            "Married": married,
            "Dependents": dependents,
            "Education": education,
            "Self_Employed": self_employed,
            "ApplicantIncome": applicant_income,
            "CoapplicantIncome": coapplicant_income,
            "LoanAmount": loan_amount,
            "Loan_Amount_Term": loan_amount_term,
            "Credit_History": credit_history,
            "Property_Area": property_area,
        }

        # Reuses main.py's predict_single() unchanged — same feature
        # engineering, encoding, and scaling used at training time.
        result = pipeline.predict_single(model, scaler, applicant)

        st.divider()
        approved = result["prediction"] == "Approved"
        prob = float(result["approval_probability"].strip("%"))

        col_a, col_b = st.columns([1, 2])
        with col_a:
            if approved:
                st.success(f"### ✅ {result['prediction']}")
            else:
                st.error(f"### ❌ {result['prediction']}")
            st.metric("Approval Probability", result["approval_probability"])
        with col_b:
            st.progress(min(max(prob / 100, 0.0), 1.0))
            st.caption("Probability the model assigns to loan approval.")

        with st.expander("Raw input sent to the model"):
            st.json(applicant)

# ----------------------------------------------------------------------
# TAB 2: Model Performance
# ----------------------------------------------------------------------
with tab_performance:
    st.subheader("Evaluation metrics")
    metrics = load_metrics()
    if metrics:
        cols = st.columns(len(metrics))
        for col, (k, v) in zip(cols, metrics.items()):
            col.metric(k.replace("_", " ").title(), f"{v:.3f}")
    else:
        st.info("Run `python main.py` first to generate outputs/metrics.json.")

    col1, col2 = st.columns(2)
    cm_path = os.path.join(OUT_DIR, "confusion_matrix.png")
    roc_path = os.path.join(OUT_DIR, "roc_curve.png")
    if os.path.exists(cm_path):
        col1.image(cm_path, caption="Confusion Matrix", use_container_width=True)
    if os.path.exists(roc_path):
        col2.image(roc_path, caption="ROC Curve", use_container_width=True)

    st.subheader("Feature importance (coefficients & odds ratios)")
    fi_path = os.path.join(OUT_DIR, "feature_importance.png")
    if os.path.exists(fi_path):
        st.image(fi_path, use_container_width=True)

    importance_df = load_importance()
    if importance_df is not None:
        st.dataframe(importance_df, use_container_width=True, hide_index=True)

# ----------------------------------------------------------------------
# TAB 3: EDA Plots
# ----------------------------------------------------------------------
with tab_eda:
    st.subheader("Exploratory Data Analysis")
    eda_files = sorted(f for f in os.listdir(OUT_DIR) if f.startswith("eda_"))
    if not eda_files:
        st.info("Run `python main.py` first to generate EDA plots in outputs/.")
    else:
        cols = st.columns(2)
        for i, fname in enumerate(eda_files):
            cols[i % 2].image(os.path.join(OUT_DIR, fname), caption=fname, use_container_width=True)

st.sidebar.header("About")
st.sidebar.write(
    "This app wraps the existing `main.py` pipeline (preprocessing, "
    "feature engineering, Logistic Regression training, and evaluation) "
    "in a Streamlit UI — none of the original project code was changed."
)
st.sidebar.write("Source: `main.py` + `src/` (unmodified).")
